def step(example: int, index: int, title: str, formula: str, scenario: str, chapter: str):
    labels = ["Represent the system", "Choose the governing relation", "Carry out the calculation", "Interpret and verify"]
    label = labels[index - 1]
    explanations = [
        f"Solution: Draw or describe the system in {scenario}, label the known and unknown quantities, and state the direction or sign convention.\n\nWhy it works: A defined system prevents quantities exchanged with the surroundings from being counted twice.",
        f"Solution: Select {formula} only after checking that its assumptions match {scenario}; isolate the requested quantity symbolically.\n\nWhy it works: The governing relation expresses the conservation law or field model that connects the givens to the unknown.",
        "Solution: Substitute values only in compatible units, keep signs attached to oriented quantities, and show the intermediate algebra before rounding.\n\nWhy it works: Dimensional consistency exposes a mismatched relation or conversion before it becomes a numerical error.",
        "Solution: State the result with units and compare it to a zero-input, large-distance, or reversed-direction limiting case appropriate to the scenario.\n\nWhy it works: A physical model must predict behavior that remains consistent when the driving condition changes.",
    ]
    media = []
    if index == 1:
        media = [{"type": "image", "src": media_path(chapter), "alt": f"Original {title} relationship map used to identify the system and governing relation.", "caption": "Use the map before writing the first equation."}]
    return {"id": f"we{example}-s{index}", "title": label, "instruction": f"{label} for {title}.", "type": "freeResponse", "prompt": f"Explain how this step advances the solution for {title}.", "answer": {"gradingMode": "selfCheck", "keyPoints": [label, "uses the stated system and relation"]}, "explanation": explanations[index - 1], "media": media}



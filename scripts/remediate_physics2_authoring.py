def common_metadata(doc: dict, chapter: str):
    learning_goal, activity_type = ACTIVITY[doc["assessmentType"]]
    doc["modeDefault"] = "practice"
    doc["randomizeQuestions"] = False
    doc["skills"] = [doc["topicId"], f"physics2-ch{chapter}-modeling"]

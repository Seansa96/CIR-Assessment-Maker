def quiz(doc: dict, chapter: str, profile: tuple):
    common_metadata(doc, chapter)
    doc["authoring"] = text_authoring("easy")
    doc["attemptQuestionCount"] = 10
    questions = doc.setdefault("questions", [])
    for index, question in enumerate(questions, 1):
        question["difficultyDimensions"] = QUIZ_DIMENSIONS[(index - 1) % len(QUIZ_DIMENSIONS)]
        question["difficultyEvidence"] = "Requires selecting the governing physical model and checking an assumption or representation."
        ensure_choice_feedback(question)
    while len(questions) < 10:
        questions.append(generated_quiz_question(len(questions) + 1, chapter, profile))



def structured_solution(solution: str, reason: str, distractors: str | None = None):
    text = f"Solution: {solution}\n\nWhy it works: {reason}"
    if distractors:
        text += f"\n\nWhy the other choices fail: {distractors}"
    return text


def ensure_choice_feedback(question: dict):
    if question.get("type") != "multipleChoice":
        return
    correct = question.get("answer", {}).get("choiceId")
    for choice in question.get("choices", []):
        if choice.get("id") != correct and not choice.get("issueSignals"):
            choice["issueSignals"] = [{"id": "physics2-method-selection-error", "domains": ["physics-2"]}]
    if "Why the other choices fail:" not in question.get("explanation", ""):
        question["explanation"] = structured_solution(
            question.get("explanation", "Select the option consistent with the stated model."),
            "The correct response follows the definition, governing relation, and stated assumptions.",
            "Each distractor omits an assumption, reverses a relation, or ignores a required unit or sign check.",
        )


def glossary(doc: dict, chapter: str, profile: tuple):
    common_metadata(doc, chapter)
    doc["authoring"] = text_authoring()
    title, theme, formula, section_titles = profile
    glossary_data = doc.setdefault("glossary", {})
    sections = glossary_data.setdefault("sections", [])
    if not sections:
        sections.append({"id": "terms", "title": "Core terms", "required": True, "content": "Use each term to describe a physical model.", "entries": []})
    entries = sections[0].setdefault("entries", [])
    for entry in entries:
        entry.setdefault("drills", [])
        if not entry["drills"]:
            entry["drills"].append({"id": f"{entry['id']}-drill", "type": "flashcard", "prompt": f"What does {entry['term']} mean?", "answer": {"expected": entry.get("definition", "")}})
        for drill in entry["drills"]:
            drill["explanation"] = structured_solution(
                entry.get("definition", "State the definition precisely."),
                f"The definition identifies how {entry.get('term', 'the term')} functions in the {title} model.",
            )
            drill.setdefault("tags", [doc["topicId"]])
    for index, section_title in enumerate(section_titles, 1):
        if len(entries) >= 14:
            break
        entry_id = f"t{len(entries) + 1:02d}"
        term = section_title
        definition = f"A {title} idea used to model {theme}; apply it with the governing relation ${formula}$ only when its assumptions and units match the situation."
        entries.append({"id": entry_id, "term": term, "definition": definition, "drills": [{"id": f"{entry_id}-drill", "type": "flashcard", "prompt": f"What role does {term} play in {title}?", "answer": {"expected": definition}, "explanation": structured_solution(definition, f"It connects {term.lower()} to the system, relation, and interpretation required by the topic."), "tags": [doc["topicId"]]}]})
    glossary_data["introduction"] = f"Use these {title} terms to identify a system, select ${formula}$ when appropriate, and explain the result."


def recall_item(item_id: str, prompt: str, answer: str, chapter: str):
    return {"id": item_id, "type": "typed", "prompt": prompt, "answer": {"expected": answer}, "explanation": structured_solution(answer, "Retrieval is useful when the response is tied to the governing relation, its assumptions, and the physical quantity being described."), "tags": [f"physics2-ch{chapter}-modeling"]}


def recall(doc: dict, chapter: str, profile: tuple):
    common_metadata(doc, chapter)
    doc["authoring"] = text_authoring()
    title, theme, formula, section_titles = profile
    items = doc.setdefault("items", [])
    for item in items:
        item["type"] = "typed" if item.get("type") not in {"typed", "cloze"} else item["type"]
        item.setdefault("answer", {}).setdefault("expected", item.get("prompt", ""))
        item["explanation"] = structured_solution(str(item["answer"].get("expected", "")), f"This retrieves a precise part of the {title} model before a calculation is attempted. It matters because the governing relation must be connected to a defined system, compatible units, and the direction or condition stated in the situation.")
        item.setdefault("tags", [doc["topicId"]])
    for section_title in section_titles:
        if len(items) >= 12:
            break
        index = len(items) + 1
        items.append(recall_item(f"r{index:02d}", f"In {title}, state the role of {section_title.lower()} and name the governing relation or condition that makes it useful.", f"{section_title} is interpreted within the {title} model of {theme}; check assumptions, units, and direction before using ${formula}$.", chapter))



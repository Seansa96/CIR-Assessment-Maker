def chapter_key(identifier: str) -> str:
    return identifier.split("-", 2)[1].replace("ch", "")


def media_path(chapter: str) -> str:
    return f"/media/physics2/ch{chapter}-relationship-map.svg"


def authoring():
    return {"visualRequirement": "required", "visualRationale": "An original relationship map supports the model, direction, and units used in this Physics 2 learning activity."}


def text_authoring(tier: str | None = None, exception: str | None = None):
    result = {
        "visualRequirement": "notApplicable",
        "visualRationale": "This text-first activity assesses vocabulary, retrieval, or written physical reasoning; an illustration would not be required to interpret any item.",
    }
    if tier:
        result["difficultyTier"] = tier
    if exception:
        result["exceptionReason"] = exception
    return result



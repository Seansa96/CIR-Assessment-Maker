def write_release_manifest(documents: list[tuple[str, dict]]):
    artifacts = []
    for _, doc in documents:
        artifacts.append({
            "id": doc["id"],
            "assessmentType": doc["assessmentType"],
            "topicId": doc["topicId"],
            "learningGoal": ACTIVITY[doc["assessmentType"]][0],
            "activityType": ACTIVITY[doc["assessmentType"]][1],
            "packetId": f"packet-physics2-ch{chapter_key(doc['id'])}-authoring-remediation-v1",
            "publicationStatus": "published",
        })
    payload = {"schemaVersion": 1, "id": "physics2-authoring-remediation-release", "categoryId": "physics-2", "sourceId": SOURCE_ID, "sourceReviewState": "approved-for-internal-derivation", "publicationStatus": "published", "artifacts": artifacts}
    path = REFERENCE / "assessment-release-manifests" / "physics2-authoring-remediation.json"
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def main():
    MEDIA.mkdir(parents=True, exist_ok=True)
    changed = []
    documents = []
    for path in sorted(ASSESSMENTS.glob("physics2-*.yaml")) + sorted(ASSESSMENTS.glob("physics2-*.json")):
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(doc, dict) or doc.get("categoryId") != "physics-2":
            continue
        if doc.get("assessmentType") not in {"conceptLesson", "workedExample", "glossary", "recallDrill", "quiz", "test"}:
            continue
        chapter = chapter_key(doc["id"])
        profile = CHAPTERS[chapter]
        if doc["assessmentType"] == "conceptLesson":
            lesson(doc, chapter, profile)
        elif doc["assessmentType"] == "workedExample":
            worked(doc, chapter, profile)
        elif doc["assessmentType"] == "glossary":
            glossary(doc, chapter, profile)
        elif doc["assessmentType"] == "recallDrill":
            recall(doc, chapter, profile)
        elif doc["assessmentType"] == "quiz":
            quiz(doc, chapter, profile)
        else:
            test(doc, chapter, profile)
        path.write_text(yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=110), encoding="utf-8")
        changed.append(doc["id"])
        documents.append((str(path), doc))
    for chapter, profile in CHAPTERS.items():
        (MEDIA / f"ch{chapter}-relationship-map.svg").write_text(svg(chapter, profile), encoding="utf-8")
    source_packets()
    write_blueprints(documents)
    write_release_manifest(documents)
    print(f"Remediated {len(changed)} Physics 2 assessments.")


if __name__ == "__main__":
    main()
